/**
 * Phase 0 테스트 멜로디 셋.
 * 각 노트: { pitch: MIDI 번호, start: 시작 비트(4/4, 1비트=4분음표), dur: 길이(비트) }
 * plan.md 10장 "못난 멜로디" 조건: (a) 음역 5도 이내 (b) 비다이어토닉 혼입 (c) 리듬 단조 반복
 */

function buildMelody({ name, type, uglyReason, bpm, sequence }) {
  let cursor = 0;
  const notes = sequence.map(([pitch, dur]) => {
    const note = { pitch, start: cursor, dur };
    cursor += dur;
    return note;
  });
  return { name, type, uglyReason, bpm, notes };
}

